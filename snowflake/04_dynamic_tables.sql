-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT branch.ID AS ENTITY_ID, branch.NAME AS ENTITY_NAME,
       branch.REGION, branch.CATEGORY, branch.RISK_TIER, branch.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.TXN_COUNT) AS TXN_COUNT,
       SUM(observation.VALUE_PHP) AS VALUE_PHP,
       SUM(observation.INCIDENT_COUNT) AS INCIDENT_COUNT,
       SUM(observation.FAILED_COUNT) AS FAILED_COUNT,
       SUM(observation.SLA_BREACHED) AS SLA_BREACH_COUNT,
       SUM(observation.AUDIT_DUE) AS AUDIT_DUE,
       SUM(observation.AUDIT_COMPLETED) AS AUDIT_COMPLETED,
       100.0 * (SUM(observation.TXN_COUNT) - SUM(observation.INCIDENT_COUNT)) / NULLIF(SUM(observation.TXN_COUNT), 0) AS INCIDENT_FREE_PCT,
       100.0 * SUM(observation.FAILED_COUNT) / NULLIF(SUM(observation.INCIDENT_COUNT), 0) AS INCIDENT_FAILURE_PCT,
       100.0 * SUM(observation.AUDIT_COMPLETED) / NULLIF(SUM(observation.AUDIT_DUE), 0) AS AUDIT_COMPLIANCE_PCT,
       AVG(observation.ATM_DOWNTIME_PCT) AS AVG_ATM_DOWNTIME_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.BRANCH_DAILY observation
JOIN RAW.BRANCHES branch ON branch.ID = observation.ENTITY_ID
GROUP BY branch.ID, branch.NAME, branch.REGION, branch.CATEGORY, branch.RISK_TIER, branch.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(TXN_COUNT) AS TXN_COUNT, SUM(VALUE_PHP) AS VALUE_PHP,
       SUM(INCIDENT_COUNT) AS INCIDENT_COUNT, SUM(FAILED_COUNT) AS FAILED_COUNT,
       100.0 * SUM(FAILED_COUNT) / NULLIF(SUM(INCIDENT_COUNT), 0) AS INCIDENT_FAILURE_PCT
FROM RAW.BRANCH_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.INCIDENT_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT INCIDENT_TYPE, SUM(INCIDENT_COUNT) AS INCIDENT_COUNT,
       SUM(FAILED_COUNT) AS FAILED_COUNT,
       SUM(SLA_BREACHED) AS SLA_BREACH_COUNT,
       SUM(VALUE_PHP) AS EXPOSED_VALUE_PHP,
       100.0 * SUM(FAILED_COUNT) / NULLIF(SUM(INCIDENT_COUNT), 0) AS INCIDENT_FAILURE_PCT
FROM RAW.BRANCH_DAILY
WHERE INCIDENT_COUNT > 0
GROUP BY INCIDENT_TYPE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(TXN_COUNT) AS TXNS, SUM(INCIDENT_COUNT) AS INCIDENTS,
         SUM(FAILED_COUNT) AS FAILED, SUM(SLA_BREACHED) AS BREACHES, SUM(VALUE_PHP) AS VALUE_PHP,
         SUM(AUDIT_DUE) AS AUDIT_DUE, SUM(AUDIT_COMPLETED) AS AUDIT_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.BRANCH_DAILY
), book AS (SELECT COUNT(*) AS BRANCH_COUNT FROM RAW.BRANCHES),
documents AS (
  SELECT 100.0 * SUM(LEAST(ON_FILE_QTY, REQUIRED_QTY)) / NULLIF(SUM(REQUIRED_QTY), 0) AS COVERAGE_PCT,
         SUM(PENDING_QTY) AS PENDING
  FROM RAW.CONTROL_DOCUMENTS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Incident-Free Transaction Rate' AS TITLE,
         100.0 * (TXNS - INCIDENTS) / NULLIF(TXNS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Incidents Raised', INCIDENTS, '' FROM observations
  UNION ALL SELECT 3, 'Failed-Transaction Incidents', FAILED, '' FROM observations
  UNION ALL SELECT 4, 'Incident Failure Rate', 100.0 * FAILED / NULLIF(INCIDENTS, 0), '%' FROM observations
  UNION ALL SELECT 5, 'SLA Breaches', BREACHES, '' FROM observations
  UNION ALL SELECT 6, 'Value Processed (PHP M)', VALUE_PHP / 1e6, '' FROM observations
  UNION ALL SELECT 7, 'Transactions Processed', TXNS, '' FROM observations
  UNION ALL SELECT 8, 'Cash Audit Compliance', 100.0 * AUDIT_COMPLETED / NULLIF(AUDIT_DUE, 0), '%' FROM observations
  UNION ALL SELECT 9, 'Branches Monitored', BRANCH_COUNT, '' FROM book
  UNION ALL SELECT 10, 'Branch Control Coverage', COVERAGE_PCT, '%' FROM documents
  UNION ALL SELECT 11, 'Control Documents Pending', PENDING, '' FROM documents
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                WHEN metrics.SORT_ORDER = 1 THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 2), '990.00'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.INCIDENT_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
